static inline uint32_t rotl(uint32_t x, int n) {
    return (x << n) | (x >> (32 - n));
}

// T-table初始化
void sm4_ttable_init(void) {
    for (int i = 0; i < 256; i++) {
        uint32_t sbox_val = SM4_SBOX[i];
        
        // L变换T-table: T(x) = τ(x) ⊕ rotl(τ(x), 2) ⊕ rotl(τ(x), 10) ⊕ rotl(τ(x), 18) ⊕ rotl(τ(x), 24)
        uint32_t l_result = sbox_val ^ rotl(sbox_val, 2) ^ rotl(sbox_val, 10) ^ rotl(sbox_val, 18) ^ rotl(sbox_val, 24);
        
        SM4_T0[i] = l_result;
        SM4_T1[i] = rotl(l_result, 8);
        SM4_T2[i] = rotl(l_result, 16);
        SM4_T3[i] = rotl(l_result, 24);
        
        // L'变换T-table: T'(x) = τ(x) ⊕ rotl(τ(x), 13) ⊕ rotl(τ(x), 23)
        uint32_t lp_result = sbox_val ^ rotl(sbox_val, 13) ^ rotl(sbox_val, 23);
        
        SM4_TK0[i] = lp_result;
        SM4_TK1[i] = rotl(lp_result, 8);
        SM4_TK2[i] = rotl(lp_result, 16);
        SM4_TK3[i] = rotl(lp_result, 24);
    }
}

// T-table密钥扩展
void sm4_ttable_keygen(const uint32_t user_key[4], uint32_t round_keys[32]) {
    uint32_t k[36];
    
    // 初始化
    for (int i = 0; i < 4; i++) {
        k[i] = user_key[i] ^ SM4_FK[i];
    }
    
    // 生成轮密钥
    for (int i = 0; i < 32; i++) {
        uint32_t tmp = k[i+1] ^ k[i+2] ^ k[i+3] ^ SM4_CK[i];
        k[i+4] = k[i] ^ (SM4_TK0[(tmp >> 24) & 0xff] ^
                         SM4_TK1[(tmp >> 16) & 0xff] ^
                         SM4_TK2[(tmp >> 8) & 0xff] ^
                         SM4_TK3[tmp & 0xff]);
        round_keys[i] = k[i+4];
    }
}

// T-table加密
void sm4_ttable_encrypt(const uint32_t plaintext[4], uint32_t ciphertext[4], const uint32_t round_keys[32]) {
    uint32_t x[36];
    
    // 初始化
    for (int i = 0; i < 4; i++) {
        x[i] = plaintext[i];
    }
    
    // 32轮加密
    for (int i = 0; i < 32; i++) {
        uint32_t tmp = x[i+1] ^ x[i+2] ^ x[i+3] ^ round_keys[i];
        x[i+4] = x[i] ^ (SM4_T0[(tmp >> 24) & 0xff] ^
                         SM4_T1[(tmp >> 16) & 0xff] ^
                         SM4_T2[(tmp >> 8) & 0xff] ^
                         SM4_T3[tmp & 0xff]);
    }
    
    // 反序变换
    for (int i = 0; i < 4; i++) {
        ciphertext[i] = x[35-i];
    }
}

// T-table解密
void sm4_ttable_decrypt(const uint32_t ciphertext[4], uint32_t plaintext[4], const uint32_t round_keys[32]) {
    uint32_t x[36];
    
    // 初始化
    for (int i = 0; i < 4; i++) {
        x[i] = ciphertext[i];
    }
    
    // 32轮解密(逆序使用轮密钥)
    for (int i = 0; i < 32; i++) {
        uint32_t tmp = x[i+1] ^ x[i+2] ^ x[i+3] ^ round_keys[31-i];
        x[i+4] = x[i] ^ (SM4_T0[(tmp >> 24) & 0xff] ^
                         SM4_T1[(tmp >> 16) & 0xff] ^
                         SM4_T2[(tmp >> 8) & 0xff] ^
                         SM4_T3[tmp & 0xff]);
    }
    
    // 反序变换
    for (int i = 0; i < 4; i++) {
        plaintext[i] = x[35-i];
    }
}